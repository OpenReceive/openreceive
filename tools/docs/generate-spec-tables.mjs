#!/usr/bin/env node

// Generates the route/error markdown tables that docs restate from the spec.
// The spec is the single source: this script reads
// spec/openapi/openreceive-http.v1.yaml and spec/schemas/error.schema.json and
// rewrites the content between `<!-- generated:<name> -->` /
// `<!-- /generated:<name> -->` markers in the registered docs files.
// Hand-written prose outside the markers is never touched.
//
// Usage:
//   node tools/docs/generate-spec-tables.mjs           # rewrite stale blocks
//   node tools/docs/generate-spec-tables.mjs --check   # exit 1 when any block is stale

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parse as parseYaml } from "yaml";

const root = process.cwd();
const check = process.argv.includes("--check");

const OPENAPI_PATH = "spec/openapi/openreceive-http.v1.yaml";
const ERROR_SCHEMA_PATH = "spec/schemas/error.schema.json";
const HTTP_METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

// Which generated blocks each docs file must carry.
const targets = {
  "docs/guides/api-reference.md": ["routes", "error-codes", "route-errors"],
  "docs/internal/shipped-routes.md": ["route-list"],
};

const GENERATED_NOTE =
  "<!-- Generated by tools/docs/generate-spec-tables.mjs from spec/. Edit the spec, then rerun the generator; never edit this block by hand. -->";

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function readFile(relativePath) {
  return readFileSync(path.join(root, relativePath), "utf8");
}

function oneLine(text) {
  return String(text ?? "")
    .replace(/\s+/g, " ")
    .trim();
}

function refName(ref) {
  const match = /^#\/components\/schemas\/([A-Za-z0-9]+)$/.exec(ref ?? "");
  assert(match, `unsupported $ref: ${ref}`);
  return match[1];
}

// Collect every operation in spec order.
function listOperations(openApi) {
  const operations = [];
  for (const [route, pathItem] of Object.entries(openApi.paths ?? {})) {
    for (const method of HTTP_METHODS) {
      const operation = pathItem?.[method];
      if (!operation) continue;
      const responses = operation.responses ?? {};
      const successStatuses = Object.keys(responses).filter((status) => status.startsWith("2"));
      const errorStatuses = Object.keys(responses).filter((status) => !status.startsWith("2"));
      assert(
        successStatuses.length === 1,
        `${method.toUpperCase()} ${route}: expected exactly one 2xx response`,
      );
      for (const status of errorStatuses) {
        assert(
          responses[status]?.$ref === "#/components/responses/Error",
          `${method.toUpperCase()} ${route}: ${status} must reference the shared Error response`,
        );
      }
      operations.push({
        method: method.toUpperCase(),
        route,
        operation,
        successStatus: successStatuses[0],
        successResponse: responses[successStatuses[0]],
        errorStatuses,
      });
    }
  }
  assert(operations.length > 0, "OpenAPI spec declares no operations");
  return operations;
}

// `{ order_id, amount_msats, fiat_quote?, payment_methods }` from an object schema.
function objectShape(schema) {
  const required = new Set(schema.required ?? []);
  const keys = Object.entries(schema.properties ?? {}).map(([key, prop]) => {
    const suffix = required.has(key) ? "" : "?";
    return prop?.$ref ? `${key}${suffix}: ${refName(prop.$ref)}` : `${key}${suffix}`;
  });
  return `{ ${keys.join(", ")} }`;
}

// One-line body-shape cell for a success response, from the spec's schema refs.
function bodyShape(entry, schemas) {
  const schema = entry.successResponse?.content?.["application/json"]?.schema;
  assert(schema, `${entry.method} ${entry.route}: success response has no JSON schema`);
  if (schema.$ref) {
    const name = refName(schema.$ref);
    const resolved = schemas[name];
    assert(resolved?.type === "object", `${name}: expected an object schema`);
    return `\`${name}\` \`${objectShape(resolved)}\``;
  }
  assert(
    schema.type === "object",
    `${entry.method} ${entry.route}: unsupported inline response schema`,
  );
  const description = oneLine(entry.successResponse.description);
  return description === "" ? "Untyped JSON object" : `Untyped JSON object — ${description}`;
}

function routeCell(entry, prefix) {
  return `\`${entry.method} ${prefix}${entry.route}\``;
}

function operationSummary(entry) {
  return oneLine(
    entry.operation.summary ?? entry.successResponse?.description ?? entry.operation.operationId,
  );
}

function table(header, rows) {
  const divider = header.map(() => "---");
  return [header, divider, ...rows].map((cells) => `| ${cells.join(" | ")} |`).join("\n");
}

function buildBlocks() {
  const openApi = parseYaml(readFile(OPENAPI_PATH));
  const errorSchema = JSON.parse(readFile(ERROR_SCHEMA_PATH));
  const schemas = openApi.components?.schemas ?? {};
  const operations = listOperations(openApi);
  const serverPrefix = openApi.servers?.[0]?.url ?? "";
  assert(serverPrefix.startsWith("/"), "OpenAPI servers[0].url must be the mount prefix");

  const errorCodes = errorSchema.properties?.code?.enum ?? [];
  assert(errorCodes.length > 0, "error.schema.json must enumerate error codes");
  assert(
    JSON.stringify(schemas.Error?.properties?.code?.enum) === JSON.stringify(errorCodes),
    "OpenAPI Error code enum drifted from spec/schemas/error.schema.json",
  );
  assert(schemas.Error?.type === "object", "OpenAPI Error schema must be an object");

  // Success table for the API reference. `…` is the configurable mount prefix.
  const routes = table(
    ["Route", "Status", "Response body"],
    operations.map((entry) => [
      routeCell(entry, "…"),
      entry.successStatus,
      bodyShape(entry, schemas),
    ]),
  );

  // Declared error statuses per route.
  const routeErrors = table(
    ["Route", "Declared error statuses"],
    operations.map((entry) => [
      routeCell(entry, "…"),
      entry.errorStatuses.map((status) => `\`${status}\``).join(", "),
    ]),
  );

  // Error body shape plus the code enum (spec/schemas/error.schema.json is
  // normative; the OpenAPI Error schema is asserted to match it above).
  const errorCodesBlock = [
    `Every error status above returns the OpenReceive error body \`${objectShape(errorSchema)}\``,
    `(normative: [\`spec/schemas/error.schema.json\`](../../${ERROR_SCHEMA_PATH})).`,
    "`code` is one of:",
    "",
    errorCodes.map((code) => `\`${code}\``).join(", "),
  ].join("\n");

  // Full route list with the default mount prefix, for the internal routes doc.
  const routeList = table(
    ["Route", "Purpose"],
    operations.map((entry) => [routeCell(entry, serverPrefix), operationSummary(entry)]),
  );

  return {
    routes,
    "route-errors": routeErrors,
    "error-codes": errorCodesBlock,
    "route-list": routeList,
  };
}

function applyBlocks(markdown, blockNames, blocks, relativePath) {
  let updated = markdown;
  for (const name of blockNames) {
    const marker = new RegExp(`<!-- generated:${name} -->[\\s\\S]*?<!-- /generated:${name} -->`);
    assert(marker.test(updated), `${relativePath}: missing <!-- generated:${name} --> block`);
    updated = updated.replace(
      marker,
      `<!-- generated:${name} -->\n${GENERATED_NOTE}\n\n${blocks[name]}\n<!-- /generated:${name} -->`,
    );
  }
  return updated;
}

const blocks = buildBlocks();
const changed = [];

for (const [relativePath, blockNames] of Object.entries(targets)) {
  const current = readFile(relativePath);
  const updated = applyBlocks(current, blockNames, blocks, relativePath);
  if (updated === current) continue;
  changed.push(relativePath);
  if (!check) {
    writeFileSync(path.join(root, relativePath), updated);
    console.log(`Updated generated spec tables in ${relativePath}.`);
  }
}

if (check && changed.length > 0) {
  console.error(
    `Generated spec tables are stale in: ${changed.join(", ")}. Run node tools/docs/generate-spec-tables.mjs.`,
  );
  process.exit(1);
}
if (changed.length === 0) {
  console.log("Generated spec tables are current.");
}
