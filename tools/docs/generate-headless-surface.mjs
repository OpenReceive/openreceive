// Rewrites the two generated blocks that keep the docs honest about the curated
// `@openreceive/browser/headless` entry module:
//
// - docs/internal/headless-surface.md — the full sorted inventory.
// - docs/guides/headless-checkout.md — the leftovers: every exported symbol the
//   public guide's hand-written sections do not name. Those sections stay
//   hand-written on purpose (they say what each group is FOR), but the guide
//   used to claim it could not drift while the curated list had drifted anyway:
//   it named six swap symbols and omitted the refund-critical ones. Generating
//   the remainder makes the claim true — a promoted symbol cannot sit
//   undocumented, and a dropped one cannot linger.
// - and, in both, what is deliberately NOT on `/headless`: the names the main
//   `@openreceive/browser` entry exports and this one does not. Completeness
//   was machine-checked in one direction only, which left a reader of the
//   headless page with no way to learn that a second entry point exists at all
//   — and the symbols that live there (`createGuestCheckoutResume`,
//   `createGuestOrderFetcher`) are exactly the ones a headless swap checkout
//   needs before it can honestly offer a refund form. The split is per-symbol
//   and reasoned (see headless.ts); the silence about it was not.
//
// `--check` fails the gate when any block is stale.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";

const root = process.cwd();
const ENTRY = "packages/js/browser/src/headless.ts";
const MAIN_ENTRY = "packages/js/browser/src/index.ts";
const TARGET = "docs/internal/headless-surface.md";
const BLOCK = "headless-symbols";
const MAIN_BLOCK = "main-entry-symbols";
const GUIDE = "docs/guides/headless-checkout.md";
const GUIDE_BLOCK = "headless-symbols-uncovered";
const GUIDE_MAIN_BLOCK = "headless-symbols-main-entry";
const GENERATED_NOTE =
  "<!-- Generated by tools/docs/generate-headless-surface.mjs from packages/js/browser/src/headless.ts. Promote or drop the symbol there, then rerun the generator; never edit this block by hand. -->";
const MAIN_GENERATED_NOTE =
  "<!-- Generated by tools/docs/generate-headless-surface.mjs by diffing packages/js/browser/src/index.ts against src/headless.ts. Move the symbol between those two entry modules, then rerun the generator; never edit this block by hand. -->";

const check = process.argv.includes("--check");

/**
 * Collects the exported names from a curated re-export module. Only the
 * `export { ... } from "..."` and `export type { ... } from "..."` forms are
 * used by the headless entry, and the module deliberately never uses
 * `export *` — which would make the surface unenumerable here and unreviewable
 * in general.
 */
export function readHeadlessSymbols(source) {
  assert(
    !/^\s*export\s+\*/m.test(source),
    `${ENTRY}: \`export *\` would make the headless surface unenumerable; list symbols explicitly`,
  );
  // Comments first. Both entry modules explain their curation inline, and the
  // main entry does it INSIDE the export braces — a `//` line between two names
  // was read as part of one, which turned a symbol list into prose fragments.
  const code = source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
  const symbols = new Set();
  for (const match of code.matchAll(/export\s+(?:type\s+)?\{([^}]*)\}/g)) {
    for (const raw of match[1].split(",")) {
      const name = raw
        .replace(/\btype\b/, "")
        .split(/\bas\b/)
        .pop()
        .trim();
      if (name.length > 0) symbols.add(name);
    }
  }
  return [...symbols].sort((left, right) => left.localeCompare(right, "en"));
}

function renderBlock(symbols) {
  const lines = [
    `The curated surface is ${symbols.length} symbols:`,
    "",
    ...symbols.map((symbol) => `- \`${symbol}\``),
  ];
  return lines.join("\n");
}

/**
 * The other direction: what `@openreceive/browser` exports and `/headless` does
 * not. Derived from the same export lists as everything above, so it cannot
 * drift from either entry module.
 */
function renderMainEntryBlock(mainOnly) {
  if (mainOnly.length === 0) {
    return "Every name on the main entry is also on `/headless`.";
  }
  return [
    `${mainOnly.length} name${mainOnly.length === 1 ? "" : "s"} on \`@openreceive/browser\``,
    "that `/headless` does not carry:",
    "",
    ...mainOnly.map((symbol) => `- \`${symbol}\``),
  ].join("\n");
}

/** Replace one `<!-- BEGIN GENERATED: name -->…<!-- END GENERATED: name -->` block. */
function replaceGeneratedBlock(document, name, body, file, note = GENERATED_NOTE) {
  const begin = `<!-- BEGIN GENERATED: ${name} -->`;
  const end = `<!-- END GENERATED: ${name} -->`;
  const marker = new RegExp(`${begin}[\\s\\S]*?${end}`);
  assert(marker.test(document), `${file}: missing ${begin} block`);
  return document.replace(marker, `${begin}\n${note}\n\n${body}\n${end}`);
}

/**
 * Fill the public guide's leftovers block: every exported symbol the guide's
 * hand-written sections do not name in backticks. The block's own contents are
 * excluded from that scan, so the output is a fixed point rather than a list
 * that erases itself on the second run.
 */
export function renderGuideBlock(guide, symbols) {
  const begin = `<!-- BEGIN GENERATED: ${GUIDE_BLOCK} -->`;
  const end = `<!-- END GENERATED: ${GUIDE_BLOCK} -->`;
  const marker = new RegExp(`${begin}[\\s\\S]*?${end}`);
  assert(marker.test(guide), `${GUIDE}: missing ${begin} block`);

  const prose = guide.replace(marker, "");
  const uncovered = symbols.filter((symbol) => !prose.includes(`\`${symbol}\``));
  const body =
    uncovered.length === 0
      ? "Every symbol on the surface is named in a section above."
      : [
          `Also on the surface, in no group above (${uncovered.length} symbols) — element`,
          "and theme plumbing, wizard/icon helpers, attribute parsers and log types:",
          "",
          ...uncovered.map((symbol) => `- \`${symbol}\``),
        ].join("\n");
  return guide.replace(marker, `${begin}\n${GENERATED_NOTE}\n\n${body}\n${end}`);
}

const source = readFileSync(path.join(root, ENTRY), "utf8");
const symbols = readHeadlessSymbols(source);
assert(symbols.length > 0, `${ENTRY}: no exported symbols found`);

const mainSymbols = readHeadlessSymbols(readFileSync(path.join(root, MAIN_ENTRY), "utf8"));
assert(mainSymbols.length > 0, `${MAIN_ENTRY}: no exported symbols found`);
const headlessSet = new Set(symbols);
const mainOnly = mainSymbols.filter((symbol) => !headlessSet.has(symbol));

const current = readFileSync(path.join(root, TARGET), "utf8");
const marker = new RegExp(`<!-- generated:${BLOCK} -->[\\s\\S]*?<!-- /generated:${BLOCK} -->`);
assert(marker.test(current), `${TARGET}: missing <!-- generated:${BLOCK} --> block`);

const updated = replaceGeneratedBlock(
  current.replace(
    marker,
    `<!-- generated:${BLOCK} -->\n${GENERATED_NOTE}\n\n${renderBlock(symbols)}\n<!-- /generated:${BLOCK} -->`,
  ),
  MAIN_BLOCK,
  renderMainEntryBlock(mainOnly),
  TARGET,
  MAIN_GENERATED_NOTE,
);

const guideCurrent = readFileSync(path.join(root, GUIDE), "utf8");
const guideUpdated = replaceGeneratedBlock(
  renderGuideBlock(guideCurrent, symbols),
  GUIDE_MAIN_BLOCK,
  renderMainEntryBlock(mainOnly),
  GUIDE,
  MAIN_GENERATED_NOTE,
);

const stale = [
  [TARGET, current, updated],
  [GUIDE, guideCurrent, guideUpdated],
].filter(([, before, after]) => before !== after);

if (stale.length === 0) {
  if (!check) console.log(`Generated headless surface in ${TARGET} and ${GUIDE} is current.`);
  process.exit(0);
}

if (check) {
  console.error(
    `Generated headless surface is stale in ${stale.map(([file]) => file).join(", ")}. ` +
      "Run node tools/docs/generate-headless-surface.mjs.",
  );
  process.exit(1);
}

for (const [file, , after] of stale) writeFileSync(path.join(root, file), after);
console.log(`Updated generated headless surface in ${stale.map(([file]) => file).join(", ")}.`);
