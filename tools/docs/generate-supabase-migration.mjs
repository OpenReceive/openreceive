#!/usr/bin/env node

// Writes docs/guides/supabase-migration.md: the SQL `openreceive scaffold
// payments --supabase` emits, published as a page. Lovable's agent has no
// terminal to run the scaffold, so its directions send it here to copy the
// migration, and a person can paste it into Supabase's SQL Editor.
//
// The SQL comes from @openreceive/core (supabasePaymentsMigrationSql), the
// one source the scaffold and the repository's storage check also use, so it
// runs under tsx: `node --import tsx tools/docs/generate-supabase-migration.mjs`.
// `--check` fails the gate when the committed page is stale.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  OPENRECEIVE_SUPABASE_FUNCTIONS_VERSION,
  supabasePaymentsMigrationSql,
} from "../../packages/js/core/src/index.ts";

const root = process.cwd();
const check = process.argv.includes("--check");
const TARGET = "docs/guides/supabase-migration.md";

const page = `# Supabase migration

<!-- Generated by tools/docs/generate-supabase-migration.mjs from @openreceive/core. Never edit it by hand: change supabasePaymentsMigrationSql, then run npm run build:docs. -->

This is the SQL that \`npx openreceive scaffold payments --supabase\` writes,
for [Supabase over HTTPS](supabase.md#supabase-over-https). Use this page when
you cannot run the scaffold, for example from Lovable, whose agent has no
terminal. It is functions version ${OPENRECEIVE_SUPABASE_FUNCTIONS_VERSION}, for \`@openreceive/http\`
0.4.23 or newer.

Save it, unchanged, as one new migration (\`supabase/migrations/<timestamp>_openreceive.sql\`),
or paste it into the Supabase SQL Editor and run it. It is safe to run again.
It creates OpenReceive's two tables with row level security on, revokes
every grant from \`anon\` and \`authenticated\`, and creates the functions the
server calls to write the tables. It also creates \`openreceive_on_paid\` as a
placeholder that refuses every settlement, unless your project already has
one. Then replace that placeholder, in a migration of your own, with the SQL
that marks your order paid: see
[Write openreceive_on_paid](supabase.md#2-write-openreceive_on_paid).

\`\`\`sql
${supabasePaymentsMigrationSql().trimEnd()}
\`\`\`
`;

const absolute = path.join(root, TARGET);
const current = (() => {
  try {
    return readFileSync(absolute, "utf8");
  } catch {
    return null;
  }
})();
if (current !== page) {
  if (check) {
    console.error(`error: ${TARGET} is stale. Run \`npm run build:docs\`.`);
    process.exit(1);
  }
  writeFileSync(absolute, page);
}
console.log(`${check ? "Checked" : "Wrote"} ${TARGET}: ${Buffer.byteLength(page, "utf8")} bytes.`);
