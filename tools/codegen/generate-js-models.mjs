#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parse as parseYaml } from "yaml";

const root = process.cwd();
const outputPath = "packages/js/core/src/generated/contracts.ts";
const wireOutputPath = "packages/js/http/src/generated/wire.ts";
const check = process.argv.includes("--check");
const EMPTY_OBJECT = Object.freeze({});

function readYaml(relativePath) {
  return parseYaml(readFileSync(path.join(root, relativePath), "utf8"));
}

function readJson(relativePath) {
  return JSON.parse(readFileSync(path.join(root, relativePath), "utf8"));
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function messageNames(asyncApi) {
  return Object.values(asyncApi.components?.messages ?? EMPTY_OBJECT)
    .map((message) => message?.name)
    .filter((name) => typeof name === "string")
    .sort((left, right) => left.localeCompare(right, "en"));
}

function json(value) {
  return JSON.stringify(value, null, 2);
}

function generate() {
  const openApi = readYaml("spec/openapi/openreceive-http.v1.yaml");
  const asyncApi = readYaml("spec/asyncapi/openreceive-events.v1.yaml");
  const errorSchema = readJson("spec/schemas/error.schema.json");
  const schemas = openApi.components?.schemas ?? EMPTY_OBJECT;
  const checkout = schemas.Checkout;
  const amount = checkout?.properties?.amount_msats;
  const paymentHash = checkout?.properties?.payment_hash;
  const paymentStatuses = schemas.PaymentStatus?.enum ?? [];
  const errorCodes = errorSchema.properties?.code?.enum ?? [];
  const events = messageNames(asyncApi);

  assert(openApi.info?.version, "OpenAPI info.version is required");
  assert(asyncApi.info?.version, "AsyncAPI info.version is required");
  assert(paymentStatuses.length > 0, "OpenAPI payment statuses are required");
  assert(errorCodes.length > 0, "OpenReceive error codes are required");
  assert(events.length > 0, "AsyncAPI event names are required");
  assert(amount?.minimum === 1000, "invoice amount minimum drifted");
  assert(amount?.maximum === 9007199254740991, "invoice amount maximum drifted");
  assert(typeof paymentHash?.pattern === "string", "payment hash pattern is required");

  return `// Generated by tools/codegen/generate-js-models.mjs. Do not edit.

export const OPENRECEIVE_HTTP_CONTRACT_VERSION = ${json(openApi.info.version)} as const;
export const OPENRECEIVE_EVENT_CONTRACT_VERSION = ${json(asyncApi.info.version)} as const;

export const OPENRECEIVE_EVENT_NAMES = ${json(events)} as const;
export type OpenReceiveGeneratedEventName = (typeof OPENRECEIVE_EVENT_NAMES)[number];

export const OPENRECEIVE_ERROR_CODES = ${json(errorCodes)} as const;
export type OpenReceiveGeneratedErrorCode = (typeof OPENRECEIVE_ERROR_CODES)[number];

export const OPENRECEIVE_PAYMENT_STATUSES = ${json(paymentStatuses)} as const;
export type OpenReceiveGeneratedPaymentStatus = (typeof OPENRECEIVE_PAYMENT_STATUSES)[number];

export const OPENRECEIVE_PAYMENT_HASH_PATTERN = ${json(paymentHash.pattern)} as const;

export const OPENRECEIVE_AMOUNT_MSATS_BOUNDARY = {
  minimum: ${amount.minimum},
  maximum: ${amount.maximum}
} as const;
`;
}

/**
 * The OpenAPI component schemas emitted as wire types. Only well-specified
 * bodies are listed: the swap/rates responses that the contract still leaves
 * as `additionalProperties: true` (open E33) get no invented shape here.
 */
const WIRE_SCHEMA_NAMES = [
  "PrepareCheckoutRequest",
  "PrepareCheckoutResponse",
  "CreateCheckoutRequest",
  "Checkout",
  "CreateCheckoutResponse",
  "PaymentCheckRequest",
  "PaymentStatus",
  "PaymentCheck",
  "SwapQuoteRequest",
  "CreateSwapRequest",
  "CreateSwapResponse",
  "OrderRequest",
  "Error",
];

function wireTypeName(schemaName) {
  return `OpenReceiveWire${schemaName}`;
}

function wireTypeForSchema(schema, indent) {
  assert(schema !== undefined && schema !== null, "wire schema is required");
  if (typeof schema.$ref === "string") {
    const match = schema.$ref.match(/^#\/components\/schemas\/([A-Za-z0-9]+)$/);
    assert(match !== null, `unsupported wire $ref: ${schema.$ref}`);
    assert(WIRE_SCHEMA_NAMES.includes(match[1]), `wire $ref to an unlisted schema: ${match[1]}`);
    return wireTypeName(match[1]);
  }
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf.map((member) => wireTypeForSchema(member, indent)).join(" | ");
  }
  switch (schema.type) {
    case "null":
      return "null";
    case "string":
      return Array.isArray(schema.enum)
        ? schema.enum.map((value) => JSON.stringify(value)).join(" | ")
        : "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `readonly (${wireTypeForSchema(schema.items ?? EMPTY_OBJECT, indent)})[]`;
    case "object":
      return wireTypeForObjectSchema(schema, indent);
    default:
      throw new Error(`unsupported wire schema type: ${JSON.stringify(schema.type)}`);
  }
}

function wireTypeForObjectSchema(schema, indent) {
  const properties = schema.properties ?? EMPTY_OBJECT;
  const required = new Set(schema.required ?? []);
  const open = schema.additionalProperties !== false;
  const names = Object.keys(properties);
  const undeclaredRequired = [...required].filter((name) => !(name in properties));
  if (names.length === 0 && undeclaredRequired.length === 0) {
    return "Record<string, unknown>";
  }
  const inner = `${indent}  `;
  const lines = [];
  if (open) lines.push(`${inner}readonly [key: string]: unknown;`);
  for (const name of names) {
    const optional = required.has(name) ? "" : "?";
    lines.push(
      `${inner}readonly ${name}${optional}: ${wireTypeForSchema(properties[name], inner)};`,
    );
  }
  // Fields the contract requires without declaring a shape for stay `unknown`.
  for (const name of undeclaredRequired) {
    lines.push(`${inner}readonly ${name}: unknown;`);
  }
  return `{\n${lines.join("\n")}\n${indent}}`;
}

function generateWire() {
  const openApi = readYaml("spec/openapi/openreceive-http.v1.yaml");
  const schemas = openApi.components?.schemas ?? EMPTY_OBJECT;
  assert(openApi.info?.version, "OpenAPI info.version is required");

  const declarations = WIRE_SCHEMA_NAMES.map((name) => {
    const schema = schemas[name];
    assert(schema !== undefined, `OpenAPI schema ${name} is required for wire types`);
    return (
      `/** Wire shape of the OpenAPI \`${name}\` schema (snake_case JSON body). */\n` +
      `export type ${wireTypeName(name)} = ${wireTypeForSchema(schema, "")};`
    );
  });

  // The refund request body is declared inline on the path rather than as a
  // named component schema; it is well-specified, so it gets a wire type too.
  const refundSchema =
    openApi.paths?.["/swaps/refunds"]?.post?.requestBody?.content?.["application/json"]?.schema;
  assert(refundSchema !== undefined, "OpenAPI /swaps/refunds request schema is required");
  declarations.push(
    "/** Wire shape of the `POST /swaps/refunds` request body (snake_case JSON body). */\n" +
      `export type OpenReceiveWireRefundSwapRequest = ${wireTypeForSchema(refundSchema, "")};`,
  );

  return `// Generated by tools/codegen/generate-js-models.mjs. Do not edit.
// Wire request/response body types for the OpenReceive HTTP contract
// (spec/openapi/openreceive-http.v1.yaml, version ${openApi.info.version}).
// The wire is snake_case; the camelCase service types are translated to these
// shapes at the HTTP serialization boundary.

${declarations.join("\n\n")}
`;
}

// The repo is biome-formatted, so the committed file must be too: format the
// generated source before writing or comparing.
function formatGenerated(source, forPath) {
  return execFileSync(
    path.join(root, "node_modules", ".bin", "biome"),
    ["format", `--stdin-file-path=${forPath}`],
    { input: source, encoding: "utf8", cwd: root },
  );
}

const outputs = [
  { relativePath: outputPath, content: formatGenerated(generate(), outputPath) },
  { relativePath: wireOutputPath, content: formatGenerated(generateWire(), wireOutputPath) },
];

let stale = false;
for (const output of outputs) {
  const absolutePath = path.join(root, output.relativePath);
  if (check) {
    const current = existsSync(absolutePath) ? readFileSync(absolutePath, "utf8") : "";
    if (current !== output.content) {
      console.error(`${output.relativePath} is stale. Run npm run generate:models.`);
      stale = true;
    }
  } else {
    mkdirSync(path.dirname(absolutePath), { recursive: true });
    writeFileSync(absolutePath, output.content);
    console.log(`Generated ${output.relativePath}.`);
  }
}

if (check) {
  if (stale) process.exit(1);
  console.log("Generated model contracts are current.");
}
