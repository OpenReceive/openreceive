/** A JSON value as a PHP 8.2 literal: single-quoted strings, list/map arrays. */
function phpLiteral(value, indent = "") {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  if (typeof value === "string") return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
  const inner = `${indent}    `;
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((item) => `${inner}${phpLiteral(item, inner)},`).join("\n")}\n${indent}]`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) return "[]";
  return `[\n${entries
    .map(([key, item]) => `${inner}${phpLiteral(key)} => ${phpLiteral(item, inner)},`)
    .join("\n")}\n${indent}]`;
}

/** A JSON value as a Python literal: tuples for lists, dicts for objects. */
function pyLiteral(value, indent = "") {
  if (value === null || value === undefined) return "None";
  if (typeof value === "boolean") return value ? "True" : "False";
  if (typeof value === "number") return String(value);
  if (typeof value === "string") return JSON.stringify(value);
  const inner = `${indent}    `;
  if (Array.isArray(value)) {
    if (value.length === 0) return "()";
    return `(\n${value.map((item) => `${inner}${pyLiteral(item, inner)},`).join("\n")}\n${indent})`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) return "{}";
  return `{\n${entries
    .map(([key, item]) => `${inner}${pyLiteral(key)}: ${pyLiteral(item, inner)},`)
    .join("\n")}\n${indent}}`;
}

