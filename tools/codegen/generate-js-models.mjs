/** The shared tables, with the integrity every rendering relies on asserted once. */
function kernelTables() {
  const tables = readJson(kernelTablesPath);
  const swap = tables.swap;
  assert(
    Array.isArray(swap?.pay_in_assets) && swap.pay_in_assets.length > 0,
    "pay_in_assets required",
  );
  assert(Array.isArray(swap?.states) && swap.states.length > 0, "swap states required");
  assert(Array.isArray(swap?.attention_reasons), "attention_reasons required");
  assert(Array.isArray(swap?.refund_reasons), "refund_reasons required");
  assert(Array.isArray(swap?.availability_reasons), "availability_reasons required");
  for (const asset of swap.pay_in_assets) {
    for (const key of ["pay_in_asset", "label", "network_label", "coin", "network"]) {
      assert(typeof asset[key] === "string" && asset[key].length > 0, `asset ${key} required`);
    }
  }
  for (const state of swap.states) {
    assert(typeof state.state === "string" && typeof state.phase === "string", "state row shape");
    assert(typeof state.terminal === "boolean", `state ${state.state}: terminal must be boolean`);
  }
  assert(Number.isInteger(tables.nwc?.transaction_page_limit), "transaction_page_limit required");
  assert(Number.isInteger(tables.nwc?.metadata_max_bytes), "metadata_max_bytes required");
  assert(Number.isInteger(tables.attempts?.expiry_grace_seconds), "expiry_grace_seconds required");
  return tables;
}

