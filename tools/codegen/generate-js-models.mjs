function wireTypeName(schemaName) {
  return `Wire${schemaName}`;
}

// The component schemas of the OpenAPI document being generated, so an allOf
// member can be inlined by $ref.
let wireSchemas = EMPTY_OBJECT;

function resolveWireRef(ref) {
  const match = ref.match(/^#\/components\/schemas\/([A-Za-z0-9]+)$/);
  assert(match !== null, `unsupported wire $ref: ${ref}`);
  return match[1];
}

/**
 * `closed` — the enclosing allOf carries `unevaluatedProperties: false`, so
 * this member gets no index signature even though it declares no
 * `additionalProperties: false` of its own (JSON Schema 2020-12 composition).
 */
function wireTypeForSchema(schema, indent, closed = false) {
  assert(schema !== undefined && schema !== null, "wire schema is required");
  if (typeof schema.$ref === "string") {
    const name = resolveWireRef(schema.$ref);
    if (closed) {
      // Inline the composed base so the closed shape is the one emitted; the
      // open base (e.g. SwapBase) is never a wire type by itself.
      const target = wireSchemas[name];
      assert(target !== undefined, `wire $ref to a missing schema: ${name}`);
      return wireTypeForSchema(target, indent, true);
    }
    assert(WIRE_SCHEMA_NAMES.includes(name), `wire $ref to an unlisted schema: ${name}`);
    return wireTypeName(name);
  }
  if (Array.isArray(schema.allOf)) {
    const memberClosed = schema.unevaluatedProperties === false;
    return schema.allOf
      .map((member) => wireTypeForSchema(member, indent, memberClosed))
      .join(" & ");
  }
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf.map((member) => wireTypeForSchema(member, indent)).join(" | ");
  }
  switch (schema.type) {
    case "null":
      return "null";
    case "string":
      return Array.isArray(schema.enum)
        ? schema.enum.map((value) => JSON.stringify(value)).join(" | ")
        : "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `readonly (${wireTypeForSchema(schema.items ?? EMPTY_OBJECT, indent)})[]`;
    case "object":
      return wireTypeForObjectSchema(schema, indent, closed);
    default:
      throw new Error(`unsupported wire schema type: ${JSON.stringify(schema.type)}`);
  }
}

function wireTypeForObjectSchema(schema, indent, closed = false) {
  const properties = schema.properties ?? EMPTY_OBJECT;
  const required = new Set(schema.required ?? []);
  const open =
    !closed && schema.additionalProperties !== false && schema.unevaluatedProperties !== false;
  const names = Object.keys(properties);
  const undeclaredRequired = [...required].filter((name) => !(name in properties));
  if (names.length === 0 && undeclaredRequired.length === 0) {
    // A pure map schema keeps its declared value type (e.g. rates: code → price).
    return typeof schema.additionalProperties === "object" && schema.additionalProperties !== null
      ? `Record<string, ${wireTypeForSchema(schema.additionalProperties, indent)}>`
      : "Record<string, unknown>";
  }
  const inner = `${indent}  `;
  const lines = [];
  if (open) lines.push(`${inner}readonly [key: string]: unknown;`);
  for (const name of names) {
    const optional = required.has(name) ? "" : "?";
    lines.push(
      `${inner}readonly ${name}${optional}: ${wireTypeForSchema(properties[name], inner)};`,
    );
  }
  // Fields the contract requires without declaring a shape for stay `unknown`.
  for (const name of undeclaredRequired) {
    lines.push(`${inner}readonly ${name}: unknown;`);
  }
  return `{\n${lines.join("\n")}\n${indent}}`;
}

function generateWire() {
  const openApi = readYaml("spec/openapi/openreceive-http.v1.yaml");
  const schemas = openApi.components?.schemas ?? EMPTY_OBJECT;
  wireSchemas = schemas;
  assert(openApi.info?.version, "OpenAPI info.version is required");

  const declarations = WIRE_SCHEMA_NAMES.map((name) => {
    const schema = schemas[name];
    assert(schema !== undefined, `OpenAPI schema ${name} is required for wire types`);
    return (
      `/** Wire shape of the OpenAPI \`${name}\` schema (snake_case JSON body). */\n` +
      `export type ${wireTypeName(name)} = ${wireTypeForSchema(schema, "")};`
    );
  });

  // The refund request body is declared inline on the path rather than as a
  // named component schema; it is well-specified, so it gets a wire type too.
  const refundSchema =
    openApi.paths?.["/swaps/refunds"]?.post?.requestBody?.content?.["application/json"]?.schema;
  assert(refundSchema !== undefined, "OpenAPI /swaps/refunds request schema is required");
  declarations.push(
    "/** Wire shape of the `POST /swaps/refunds` request body (snake_case JSON body). */\n" +
      `export type WireRefundSwapRequest = ${wireTypeForSchema(refundSchema, "")};`,
  );

  return `// Generated by tools/codegen/generate-js-models.mjs. Do not edit.
// Wire request/response body types for the OpenReceive HTTP contract
// (spec/openapi/openreceive-http.v1.yaml, version ${openApi.info.version}).
// The wire is snake_case; the camelCase service types are translated to these
// shapes at the HTTP serialization boundary.

${declarations.join("\n\n")}
`;
}

// The repo is biome-formatted, so the committed file must be too: format the
