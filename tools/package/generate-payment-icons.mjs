#!/usr/bin/env node

// Inlines the payment-method icons into @openreceive/browser.
//
// packages/js/browser/src/assets/icons/*.svg is the source of truth; this
// writes src/generated/payment-icon-svgs.ts (committed, like compiled-styles.ts)
// with the id list and each icon's minified markup as a JS string. The
// checkout renderer draws those strings inline in its shadow root and the
// `paymentIconUrls` table derives `data:` URIs from them, so a host bundler
// never has to find, copy or serve an icon file. The .svg files still ship in
// dist/assets/icons for hosts that serve them and pass `assetBaseUrl`.
//
// Inline SVG is not <img>: markup injected into a document can carry script,
// event handlers, foreign content and external references. These strings are
// first-party and pinned at build time, and the gate below is what keeps that
// promise — an icon that trips it fails the build instead of shipping.
//
// `--check` fails when the committed module is stale (CI runs it with the
// other generators).

import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { root } from "../shared/root.mjs";

const browserRoot = path.join(root, "packages/js/browser");
const iconsDir = path.join(browserRoot, "src/assets/icons");
const generatedDir = path.join(browserRoot, "src/generated");
const generatedTs = path.join(generatedDir, "payment-icon-svgs.ts");
const header = "/* Generated by tools/package/generate-payment-icons.mjs — do not edit. */";

/**
 * The inline-SVG safety gate. Returns the reasons an icon must not be inlined;
 * an empty list means it is safe. Exported so the test suite can prove the
 * gate rejects what it claims to.
 */
export function inlineSvgViolations(svg) {
  const violations = [];
  if (/<script\b/i.test(svg)) violations.push("contains <script>");
  if (/\son[a-z]+\s*=/i.test(svg)) violations.push("contains an on*= event handler attribute");
  if (/<foreignObject\b/i.test(svg)) violations.push("contains <foreignObject>");
  if (/<style\b/i.test(svg))
    violations.push("contains <style> (would apply to the whole shadow root)");
  if (/<image\b/i.test(svg)) violations.push("contains <image> (an external load)");
  for (const match of svg.matchAll(/\b(?:xlink:)?href\s*=\s*"([^"]*)"/gi)) {
    if (!match[1].startsWith("#")) violations.push(`external href "${match[1]}"`);
  }
  if (/javascript:/i.test(svg)) violations.push("contains a javascript: URL");
  return violations;
}

/** Whitespace-only minification: the markup stays readable and byte-stable. */
export function minifySvg(svg) {
  return svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim();
}

function readIcons() {
  const files = readdirSync(iconsDir)
    .filter((file) => file.endsWith(".svg"))
    .sort();
  if (files.length === 0) throw new Error(`generate-payment-icons: no icons in ${iconsDir}`);
  const failures = [];
  const seenIds = new Map();
  const icons = files.map((file) => {
    const id = file.slice(0, -".svg".length);
    if (!/^[a-z][a-z0-9]*$/.test(id)) {
      failures.push(`${file}: icon file names must be lowercase alphanumerics`);
    }
    const svg = minifySvg(readFileSync(path.join(iconsDir, file), "utf8"));
    if (!/^<svg\b[\s\S]*<\/svg>$/.test(svg)) failures.push(`${file}: not a single <svg> document`);
    for (const violation of inlineSvgViolations(svg)) failures.push(`${file}: ${violation}`);
    // Every internal id has to be unique across the whole set: the renderer
    // can draw several icons into ONE shadow root, where `url(#g)` finds the
    // first element with that id regardless of which icon declared it.
    for (const [, internalId] of svg.matchAll(/\sid="([^"]*)"/g)) {
      const owner = seenIds.get(internalId);
      if (owner !== undefined && owner !== file) {
        failures.push(`${file}: internal id "${internalId}" collides with ${owner}`);
      }
      seenIds.set(internalId, file);
    }
    return { id, svg };
  });
  if (failures.length > 0) {
    throw new Error(`generate-payment-icons: refusing to inline\n  ${failures.join("\n  ")}`);
  }
  return icons;
}

export function renderModule(icons) {
  const ids = icons.map(({ id }) => JSON.stringify(id)).join(", ");
  const entries = icons.map(({ id, svg }) => `  ${id}: ${JSON.stringify(svg)},`).join("\n");
  return `${header}
// Source: packages/js/browser/src/assets/icons/*.svg. Edit the .svg, then run
// \`npm run generate:payment-icons\`.
export const OPENRECEIVE_PAYMENT_ICON_IDS = [${ids}] as const;
export type PaymentIconId = (typeof OPENRECEIVE_PAYMENT_ICON_IDS)[number];

/** Each packaged payment icon as minified SVG markup, keyed by id. */
export const paymentIconSvgs: Readonly<Record<PaymentIconId, string>> = Object.freeze({
${entries}
});
`;
}

function formatWithBiome(source) {
  const formatted = spawnSync(
    path.join(root, "node_modules/.bin/biome"),
    ["format", `--stdin-file-path=${generatedTs}`],
    { input: source, encoding: "utf8", cwd: root },
  );
  if (formatted.error !== undefined || formatted.status !== 0) {
    process.stderr.write(formatted.stdout ?? "");
    process.stderr.write(formatted.stderr ?? "");
    throw new Error(
      `generate-payment-icons: biome format failed for ${path.relative(root, generatedTs)}${
        formatted.error === undefined ? "" : ` (${formatted.error.message})`
      }`,
    );
  }
  return formatted.stdout;
}

export function generatePaymentIconsModule() {
  return formatWithBiome(renderModule(readIcons()));
}

function main() {
  const check = process.argv.includes("--check");
  const expected = generatePaymentIconsModule();
  if (check) {
    let current = "";
    try {
      current = readFileSync(generatedTs, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== expected) {
      console.error(
        `${path.relative(root, generatedTs)} is stale; run npm run generate:payment-icons`,
      );
      process.exit(1);
    }
    return;
  }
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(generatedTs, expected);
  process.stdout.write(`generated ${path.relative(root, generatedTs)}\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
