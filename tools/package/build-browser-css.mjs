#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { root } from "../shared/root.mjs";
import { STYLE_ROOT_ATTRIBUTE, scopeStyles } from "./scope-styles.mjs";

const browserRoot = path.join(root, "packages/js/browser");
const input = path.join(browserRoot, "src/styles.source.css");
const distCss = path.join(browserRoot, "dist/styles.css");
const srcCss = path.join(browserRoot, "src/styles.css");
const generatedDir = path.join(browserRoot, "src/generated");
const generatedTs = path.join(generatedDir, "compiled-styles.ts");
// Two shapes, on purpose — tools/validate/package-smoke.mjs pins both.
//
// elements and react ship the compiled sheet as a REAL FILE, because their
// stylesheet has to work without a bundler: `<link rel="stylesheet"
// href=".../@openreceive/elements/styles.css">` is the drop-in story, and a
// runtime `@import "@openreceive/browser/styles.css"` (a bare specifier) would
// 404 there. A self-contained file also means no bundler needs its export map
// resolved for it (Next's CSS resolver, for one, does not read export maps).
//
// vue, svelte and angular ship the one-line `@import` forwarder instead: their
// SFC/component formats are bundler-only by construction, so the specifier
// always resolves and there is nothing to duplicate.
//
// Neither copy can go stale: both are written HERE, from the one Tailwind
// compile below, on every package build, under a "do not edit" stamp.
//
// Scoped vs. shadow: the compile is global (preflight on `*`, `:root` variable
// dumps, daisyUI's `.btn`). Every FILE copy goes through scope-styles.mjs
// first, so importing it into a host page touches nothing outside an element
// carrying `data-openreceive-root` — a Mantine or Bootstrap host keeps its own
// paddings and buttons. src/generated/compiled-styles.ts, injected into the
// custom elements' shadow roots, gets the UNSCOPED compile: there the shadow
// boundary is the scope and the preflight is wanted. package-smoke pins both.
const wrapperCssTargets = [
  path.join(root, "packages/js/elements/src/styles.css"),
  path.join(root, "packages/js/react/src/styles.css"),
];

mkdirSync(path.dirname(distCss), { recursive: true });
mkdirSync(generatedDir, { recursive: true });

const cli = path.join(root, "node_modules/@tailwindcss/cli/dist/index.mjs");
const result = spawnSync(process.execPath, [cli, "-i", input, "-o", distCss, "--minify"], {
  cwd: browserRoot,
  encoding: "utf8",
});

if (result.status !== 0) {
  process.stderr.write(result.stdout ?? "");
  process.stderr.write(result.stderr ?? "");
  process.exit(result.status ?? 1);
}

const header = "/* Generated by tools/package/build-browser-css.mjs — do not edit. */";
const scopedHeader = `${header}\n/* Scoped: every rule applies only inside [${STYLE_ROOT_ATTRIBUTE}]. */`;
const css = readFileSync(distCss, "utf8");
const scopedCss = scopeStyles(css);
// Every copy carries the same stamp so a hand edit is obvious and a freshness
// check has something to key on. The package build compiles Tailwind once, here,
// before tsup; tsup --clean then wipes dist/styles.css and copy-static restores
// it from the committed src/styles.css.
writeFileSync(distCss, `${scopedHeader}\n${scopedCss}`);
writeFileSync(srcCss, `${scopedHeader}\n${scopedCss}`);
for (const target of wrapperCssTargets) {
  writeFileSync(target, `${scopedHeader}\n${scopedCss}`);
}
// The repo is biome-formatted; format the generated module so a rebuild never
// leaves the tree failing format:check. A biome failure fails the build —
// silently writing unformatted output would leave format:check failing later
// with no pointer back to the real cause.
const generatedSource = `${header}\nexport const compiledStyles = ${JSON.stringify(css)};\n`;
const formatted = spawnSync(
  path.join(root, "node_modules/.bin/biome"),
  ["format", `--stdin-file-path=${generatedTs}`],
  { input: generatedSource, encoding: "utf8", cwd: root },
);
if (formatted.error !== undefined || formatted.status !== 0) {
  process.stderr.write(formatted.stdout ?? "");
  process.stderr.write(formatted.stderr ?? "");
  console.error(
    `build-browser-css: biome format failed for ${path.relative(root, generatedTs)}${
      formatted.error === undefined ? "" : ` (${formatted.error.message})`
    }`,
  );
  process.exit(formatted.status ?? 1);
}
writeFileSync(generatedTs, formatted.stdout);

process.stdout.write(
  `built browser css (${css.length} bytes shadow, ${scopedCss.length} bytes scoped)\n`,
);
