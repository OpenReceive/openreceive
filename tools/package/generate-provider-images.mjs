#!/usr/bin/env node

// Inlines the provider images into @openreceive/provider-data.
//
// Everything the checkout draws ships inside the JavaScript. The payment-method
// icons are inline SVG in @openreceive/browser (generate-payment-icons.mjs);
// the wallet logos and pay-tutorial screenshots are WebP, so they ship as
// `data:image/webp;base64,…` URIs. This reads the checked-in, pre-compressed
// source images and writes two committed modules:
//
//   src/generated/provider-icon-images.ts   providerIconImages, keyed by the
//                                           registry `icon_path` — in the main
//                                           bundle, loaded with the JS
//   src/generated/pay-tutorial-images.ts    payTutorialImages, keyed by the
//                                           tutorial `path` — reached only
//                                           through a dynamic import(); hosts
//                                           with code splitting fetch it on first
//                                           open, single-file builds inline it
//
// No host copies, serves or resolves an image file, under any bundler or with
// none. Pure Node: base64 only, no image toolchain. The byte budgets below are
// what keep the bundle from bloating silently — an image over budget fails the
// build and prints the cwebp command that fixes it.
//
// Encoding recipe (source images are encoded once, by hand, and checked in):
//   wallet logo:  cwebp -q 80 -m 6 -af -sharp_yuv -resize 72 0 in.png -o out.webp
//                 (downscale only — never upscale a favicon smaller than 72 px:
//                 drop `-resize` when the source is already ≤ 72 px wide)
//   tutorial:     cwebp -q 40 -m 6 -af -sharp_yuv -resize 0 800 in.png -o out.webp
//
// `--check` fails when either committed module is stale (CI runs it with the
// other generators).

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { root } from "../shared/root.mjs";
import { formatWithBiome } from "./format-generated.mjs";

const NAME = "generate-provider-images";
const packageRoot = path.join(root, "packages/js/provider-data");
const generatedDir = path.join(packageRoot, "src/generated");
const header = `/* Generated by tools/package/${NAME}.mjs — do not edit. */`;

const KIB = 1024;

/** The two image sets, each with its directory, registry key prefix and byte budgets. */
export const IMAGE_SETS = [
  {
    kind: "wallet logo",
    dir: "src/assets/provider-icons",
    keyPrefix: "assets/provider-icons/",
    file: "provider-icon-images.ts",
    exportName: "providerIconImages",
    maxFileBytes: 4 * KIB,
    maxTotalBytes: 48 * KIB,
    cwebp: "cwebp -q 80 -m 6 -af -sharp_yuv -resize 72 0",
  },
  {
    kind: "tutorial",
    dir: "src/assets/pay_tutorials",
    keyPrefix: "assets/pay_tutorials/",
    file: "pay-tutorial-images.ts",
    exportName: "payTutorialImages",
    maxFileBytes: 48 * KIB,
    maxTotalBytes: 240 * KIB,
    cwebp: "cwebp -q 40 -m 6 -af -sharp_yuv -resize 0 800",
  },
];

function readImageSet(set) {
  const dir = path.join(packageRoot, set.dir);
  const files = readdirSync(dir)
    .filter((file) => !file.startsWith("."))
    .sort();
  if (files.length === 0) throw new Error(`${NAME}: no images in ${path.relative(root, dir)}`);
  const failures = [];
  let total = 0;
  const images = files.map((file) => {
    const relative = path.relative(root, path.join(dir, file));
    if (!file.endsWith(".webp")) {
      failures.push(`${relative}: only .webp images ship (encode it: ${set.cwebp} in -o out.webp)`);
      return { file, bytes: Buffer.alloc(0) };
    }
    const bytes = readFileSync(path.join(dir, file));
    total += bytes.length;
    if (bytes.length > set.maxFileBytes) {
      failures.push(
        `${relative}: ${bytes.length} bytes exceeds the ${set.kind} budget of ${set.maxFileBytes} ` +
          `bytes; re-encode smaller: ${set.cwebp} <source> -o ${relative}`,
      );
    }
    return { file, bytes };
  });
  if (total > set.maxTotalBytes) {
    failures.push(
      `${path.relative(root, dir)}: ${total} bytes across ${files.length} files exceeds the ` +
        `${set.kind} total budget of ${set.maxTotalBytes} bytes`,
    );
  }
  if (failures.length > 0) {
    throw new Error(`${NAME}: refusing to inline\n  ${failures.join("\n  ")}`);
  }
  return images;
}

export function renderModule(set, images) {
  const entries = images
    .map(
      ({ file, bytes }) =>
        `  ${JSON.stringify(`${set.keyPrefix}${file}`)}: ${JSON.stringify(
          `data:image/webp;base64,${bytes.toString("base64")}`,
        )},`,
    )
    .join("\n");
  return `${header}
// Source: packages/js/provider-data/${set.dir}/*.webp. Replace the .webp, then
// run \`npm run generate:provider-images\`.

/** Each packaged ${set.kind} as a \`data:image/webp;base64\` URI, keyed by its registry path. */
export const ${set.exportName}: Readonly<Record<string, string>> = Object.freeze({
${entries}
});
`;
}

export function generateProviderImageModules() {
  return IMAGE_SETS.map((set) => {
    const target = path.join(generatedDir, set.file);
    return { target, source: formatWithBiome(renderModule(set, readImageSet(set)), target, NAME) };
  });
}

function main() {
  const check = process.argv.includes("--check");
  const modules = generateProviderImageModules();
  if (check) {
    let stale = false;
    for (const { target, source } of modules) {
      let current = "";
      try {
        current = readFileSync(target, "utf8");
      } catch {
        // missing counts as stale
      }
      if (current !== source) {
        stale = true;
        console.error(
          `${path.relative(root, target)} is stale; run npm run generate:provider-images`,
        );
      }
    }
    if (stale) process.exit(1);
    return;
  }
  mkdirSync(generatedDir, { recursive: true });
  for (const { target, source } of modules) {
    writeFileSync(target, source);
    process.stdout.write(`generated ${path.relative(root, target)}\n`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
