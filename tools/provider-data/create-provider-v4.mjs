import { readdir, readFile, writeFile } from "node:fs/promises";

// Regenerates everything derived from the provider registry:
//   - the registry JSON itself (normalized formatting)
//   - tools/provider-data/provider-icons.manifest.json, the input
//     download-provider-icons.mjs reads
//   - packages/js/provider-data/src/provider-icons.ts
// Shipped package assets are never written here: manifest.json is a tool input,
// not something publishes should carry.
const registryPath = "packages/js/provider-data/src/data/openreceive-providers.v4.json";
const manifestPath = "tools/provider-data/provider-icons.manifest.json";
const iconModulePath = "packages/js/provider-data/src/provider-icons.ts";
const iconDir = "packages/js/provider-data/src/assets/provider-icons";

const registry = JSON.parse(await readFile(registryPath, "utf8"));

await writeFile(registryPath, `${JSON.stringify(registry, null, 2)}\n`);

const iconManifest = Object.fromEntries(
  Object.values(registry.providers).map((provider) => [
    provider.id,
    {
      url: provider.url,
      icon_path: provider.icon_path,
      favicon_url: `https://www.google.com/s2/favicons?domain=${new URL(provider.url).hostname}&sz=128`,
    },
  ]),
);
await writeFile(manifestPath, `${JSON.stringify(iconManifest, null, 2)}\n`);

// The shipped map lists exactly what the registry references: icons for
// removed providers must be deleted, not carried along as dead package weight
// (a test pins the map, the registry, and the directory to each other).
const iconFiles = [
  ...new Set(
    Object.values(registry.providers).map((provider) => provider.icon_path.split("/").pop()),
  ),
].sort();
const onDisk = new Set((await readdir(iconDir)).filter((file) => file.endsWith(".png")));
for (const file of iconFiles) {
  if (!onDisk.has(file)) {
    throw new Error(`registry references missing provider icon: ${iconDir}/${file}`);
  }
}
for (const file of onDisk) {
  if (!iconFiles.includes(file)) {
    throw new Error(`orphaned provider icon not referenced by the registry: ${iconDir}/${file}`);
  }
}
const iconModule = `import { assetUrl } from "./asset-url.ts";

// Generated by tools/provider-data/create-provider-v4.mjs — do not edit.
// One filename list drives the whole map; it mirrors the registry's
// icon_path references exactly (a test pins this list to the assets
// directory contents so they cannot drift).
export const OPENRECEIVE_PROVIDER_ICON_FILES: readonly string[] = [
${iconFiles.map((file) => `  "${file}",`).join("\n")}
];

export const providerIconUrls: Readonly<Record<string, string>> = Object.fromEntries(
  OPENRECEIVE_PROVIDER_ICON_FILES.map((file) => [
    \`assets/provider-icons/\${file}\`,
    assetUrl(\`./assets/provider-icons/\${file}\`),
  ]),
);
`;
await writeFile(iconModulePath, iconModule);
